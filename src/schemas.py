"""Pydantic schemas shared by every agent in the pipeline."""
from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field


# ---------- Job analysis ----------
class Requirement(BaseModel):
    name: str = Field(description="Short skill/requirement, e.g. 'Docker' or '3+ years Python'")
    kind: Literal[
        "hard_skill", "soft_skill", "experience", "education", "language", "other"
    ] = "other"
    importance: int = Field(3, ge=1, le=5, description="1 = nice to have, 5 = essential")


class JobProfile(BaseModel):
    title: str
    company: str = ""
    seniority: str = Field("", description="intern, junior, mid, senior...")
    language: str = Field("en", description="ISO code of the language the offer is written in")
    requirements: list[Requirement]
    keywords: list[str] = Field(description="ATS keywords: tools, technologies, key terms")


# ---------- Retrieval ----------
class EvidenceChunk(BaseModel):
    id: str
    text: str
    source: str
    score: float = 0.0


class EvidencePack(BaseModel):
    chunks: dict[str, EvidenceChunk] = Field(default_factory=dict)
    by_requirement: dict[str, list[str]] = Field(default_factory=dict)

    def text(self) -> str:
        return "\n".join(c.text for c in self.chunks.values())


# ---------- Generated CV ----------
class CVBullet(BaseModel):
    text: str
    source_ids: list[str] = Field(
        default_factory=list, description="IDs of the evidence chunks that support this bullet"
    )


class CVEntry(BaseModel):
    title: str
    organization: str = ""
    period: str = ""
    bullets: list[CVBullet] = Field(default_factory=list)


class GeneratedCV(BaseModel):
    headline: str
    summary: str
    skills: list[str]
    experiences: list[CVEntry] = Field(default_factory=list)
    projects: list[CVEntry] = Field(default_factory=list)
    education: list[str] = Field(
        default_factory=list,
        description="One plain-text string per degree, e.g. 'Engineering degree in Data Science, "
        "Example School (2022-2027)'. Each item is a string, never an object.",
    )
    languages: list[str] = Field(
        default_factory=list,
        description="One plain-text string per language with its level, e.g. 'French (fluent)'. "
        "Each item is a string, never an object.",
    )


# ---------- Critic ----------
class BulletVerdict(BaseModel):
    bullet: str
    supported: bool = Field(description="True only if the evidence clearly supports every claim")
    reason: str = ""


class JudgeOutput(BaseModel):
    """Raw output of the LLM judge (before programmatic checks are added)."""

    verdicts: list[BulletVerdict]
    summary_supported: bool = Field(
        True, description="True only if every claim of the summary is supported by the evidence"
    )
    summary_issue: str = Field("", description="Which summary claim is unsupported, if any")
    unsupported_titles: list[str] = Field(
        default_factory=list,
        description="Entry titles, copied exactly, whose role or project name is not in the evidence",
    )
    quality_score: int = Field(ge=1, le=10, description="Clarity, impact, action verbs, metrics")
    quality_feedback: str


class Critique(BaseModel):
    faithfulness: float
    ats: float
    quality: float
    overall: float
    unsupported: list[str] = Field(default_factory=list)
    unsupported_bullets: list[str] = Field(default_factory=list)  # exact bullet texts
    unsupported_skills: list[str] = Field(default_factory=list)
    unsupported_titles: list[str] = Field(default_factory=list)
    summary_supported: bool = True
    missing_keywords: list[str] = Field(default_factory=list)
    feedback: str = ""
    passed: bool = False


class Candidate(BaseModel):
    """Contact details are supplied by the user, never generated by the LLM."""

    name: str
    email: str = ""
    phone: str = ""
    location: str = ""
    links: list[str] = Field(default_factory=list)
